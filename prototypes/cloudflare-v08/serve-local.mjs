import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {directory, setupLocalSecrets} from './build.mjs';
import {MemoryKV,MemoryLimiter,prepare,startLocal} from './local-harness.mjs';
const {worker,a}=await prepare();await setupLocalSecrets();
const {accessCode}=JSON.parse(await readFile(path.join(directory,'dist/local-secrets.json'),'utf8'));
const kv=new MemoryKV();await kv.put('schedule:active',a);
const server=await startLocal({ACCESS_CODE:accessCode,LOGIN_LIMITER:new MemoryLimiter(),SCHEDULE_KV:kv,SESSION_TTL_SECONDS:3600},worker);
console.log(`Local synthetic-only HTTPS harness: ${server.origin}`);
console.log('Self-signed localhost certificate; Chrome test contexts accept it without changing system trust.');
console.log('Read the local access code from ignored dist/local-secrets.json. No Cloudflare connection. Ctrl+C to stop.');
process.on('SIGINT',async()=>{await server.close();process.exit(0);});
